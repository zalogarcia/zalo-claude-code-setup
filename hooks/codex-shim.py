#!/usr/bin/env python3
"""Codex -> Claude hook payload shim.

Why this exists
---------------
Codex has no Edit/Write/MultiEdit tools. Every file change goes through ONE
tool called `apply_patch`, whose `tool_input` is `{"command": "*** Begin Patch
... *** End Patch"}`. So a Claude hook registered on `Edit|Write|MultiEdit`
never fires in Codex, and if you naively re-register it on `apply_patch` it
gets a payload with no `file_path` and no written text, which every one of
those guards reads. It would no-op silently, which is worse than not porting
it: the guard would LOOK ported.

This shim sits between Codex and the unmodified Claude hook. It parses the
patch, and for each file the patch touches it synthesizes a Claude-shaped
payload and pipes that into the real hook. Deny semantics are preserved: the
first hook invocation that denies wins, and nothing after it runs.

It also translates the transcript. Codex rollout JSONL is not Claude
transcript JSONL, and two hooks (emdash-guard reading the brief,
continue-if-incomplete reading the last assistant turn) parse the transcript
directly. Without translation they read nothing and silently pass. The shim
writes a Claude-shaped projection of the rollout to a cache under the temp dir
and rewrites `transcript_path` to point at it.

Usage (from ~/.codex/hooks.json, generated by ~/.claude/scripts/codex-sync.py):

    python3 ~/.claude/hooks/codex-shim.py -- python3 ~/.claude/hooks/emdash-guard.py
    python3 ~/.claude/hooks/codex-shim.py --b64 <base64 of a shell command>

The `--b64` form exists because the outer shell that runs the hooks.json
command string would otherwise expand `$(...)`, backticks and quotes inside a
wrapped one-liner before this script ever saw them.

Set CODEX_SHIM_LOG=/path/to/log to trace decisions.

Fails OPEN on anything it does not understand: an unparseable patch is
forwarded verbatim rather than dropped.
"""

import base64
import json
import os
import subprocess
import sys
import tempfile
import time

MAX_FILES_PER_PATCH = 40  # a runaway patch must not fork 500 guard processes

SYNTHETIC_USER_PREFIXES = (
    "<recommended_plugins>",
    "<environment_context>",
    "<user_instructions>",
    "<skills_instructions>",
    "<multi_agent_mode>",
    "<plugins_instructions>",
    "<apps_instructions>",
    # Measured over the 27 rollouts on this Mac: 6 sessions opened with
    # <user_action> and 2 with <image ...>, both landing as translated user
    # turn 0 and eating one of emdash-guard's 6-turn brief window.
    "<user_action>",
    "<image ",
)


def log(msg):
    path = os.environ.get("CODEX_SHIM_LOG")
    if not path:
        return
    try:
        with open(path, "a", encoding="utf-8") as f:
            f.write("%s %s\n" % (time.strftime("%H:%M:%S"), msg))
    except OSError:
        pass


# --------------------------------------------------------------------------
# patch parsing
# --------------------------------------------------------------------------


def patch_text_of(tool_input):
    """The patch body, wherever Codex decided to put it."""
    if isinstance(tool_input, str):
        return tool_input
    if not isinstance(tool_input, dict):
        return ""
    for key in ("command", "patch", "input", "content"):
        val = tool_input.get(key)
        if isinstance(val, str) and "*** " in val:
            return val
    return ""


def parse_patch(text, cwd):
    """-> [{kind, path, added, removed}] for every file the patch touches.

    kind is 'add' | 'update' | 'delete'. Paths are absolutised against cwd.
    Returns [] when the text is not a patch this shim understands, which the
    caller treats as "fail open, forward verbatim".
    """
    if not isinstance(text, str) or "*** " not in text:
        return []

    def absolutise(p):
        p = p.strip()
        if not p:
            return ""
        p = os.path.expanduser(p)
        if not os.path.isabs(p):
            p = os.path.join(cwd or os.getcwd(), p)
        return os.path.normpath(p)

    ops = []
    cur = None
    for raw in text.splitlines():
        if raw.startswith("*** "):
            header = raw[4:].strip()
            if header in ("Begin Patch", "End Patch"):
                if header == "End Patch":
                    cur = None
                continue
            if header.startswith("Add File:"):
                cur = {"kind": "add", "path": absolutise(header[len("Add File:"):]),
                       "added": [], "removed": []}
                ops.append(cur)
            elif header.startswith("Update File:"):
                cur = {"kind": "update", "path": absolutise(header[len("Update File:"):]),
                       "added": [], "removed": []}
                ops.append(cur)
            elif header.startswith("Delete File:"):
                cur = {"kind": "delete", "path": absolutise(header[len("Delete File:"):]),
                       "added": [], "removed": []}
                ops.append(cur)
            elif header.startswith("Move to:"):
                # The content lands at the NEW path, so that is the path the
                # guards should judge.
                if cur is not None:
                    cur["path"] = absolutise(header[len("Move to:"):])
            else:
                # An unrecognised marker (e.g. "*** End of File") is NOT a
                # section terminator. Dropping the rest of the section would
                # hand the guard a truncated version of what was written,
                # which is how a guard passes text it should have blocked.
                pass
            continue
        if cur is None:
            continue
        if raw.startswith("+"):
            cur["added"].append(raw[1:])
        elif raw.startswith("-"):
            cur["removed"].append(raw[1:])
        # ' ' context lines and '@@' hunk markers carry no written text

    return [o for o in ops if o["path"]]


# --------------------------------------------------------------------------
# transcript translation
# --------------------------------------------------------------------------


def _cache_dir():
    d = os.path.join(tempfile.gettempdir(), "codex-shim-transcripts-%d" % os.getuid())
    os.makedirs(d, exist_ok=True)
    return d


def _text_of_content(content):
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    parts = []
    for block in content:
        if isinstance(block, str):
            parts.append(block)
        elif isinstance(block, dict) and isinstance(block.get("text"), str):
            parts.append(block["text"])
    return "\n".join(parts)


def translate_transcript(rollout_path, session_id, extra_assistant=None):
    """Project a Codex rollout JSONL into Claude transcript shape.

    Claude hooks expect one JSON object per line with
    {"type": "user"|"assistant", "message": {"content": [{"type": "text", ...}]}}.
    Returns the projection path, or the original path when translation is not
    possible (fail open).
    """
    if not rollout_path or not os.path.isfile(rollout_path):
        return rollout_path
    safe = "".join(c for c in str(session_id or "unknown") if c.isalnum() or c in "-_")
    out_path = os.path.join(_cache_dir(), (safe or "unknown") + ".jsonl")

    lines = []
    try:
        with open(rollout_path, encoding="utf-8", errors="replace") as f:
            for raw in f:
                raw = raw.strip()
                if not raw:
                    continue
                try:
                    rec = json.loads(raw)
                except json.JSONDecodeError:
                    continue
                if not isinstance(rec, dict) or rec.get("type") != "response_item":
                    continue
                payload = rec.get("payload")
                if not isinstance(payload, dict) or payload.get("type") != "message":
                    continue
                role = payload.get("role")
                if role not in ("user", "assistant"):
                    continue
                text = _text_of_content(payload.get("content"))
                if not text.strip():
                    continue
                if role == "user" and text.lstrip().startswith(SYNTHETIC_USER_PREFIXES):
                    continue
                lines.append(json.dumps({
                    "type": role,
                    "message": {"content": [{"type": "text", "text": text}]},
                }, ensure_ascii=False))
    except OSError:
        return rollout_path

    if isinstance(extra_assistant, str) and extra_assistant.strip():
        lines.append(json.dumps({
            "type": "assistant",
            "message": {"content": [{"type": "text", "text": extra_assistant}]},
        }, ensure_ascii=False))

    if not lines:
        return rollout_path
    try:
        tmp = out_path + ".tmp.%d" % os.getpid()
        with open(tmp, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        os.replace(tmp, out_path)
    except OSError:
        return rollout_path
    return out_path


# --------------------------------------------------------------------------
# payload synthesis
# --------------------------------------------------------------------------


def synth_payloads(payload):
    """-> list of Claude-shaped payloads, or [] to forward verbatim."""
    tool_input = payload.get("tool_input")
    cwd = payload.get("cwd") or os.getcwd()
    ops = parse_patch(patch_text_of(tool_input), cwd)
    if not ops:
        return []

    transcript = translate_transcript(payload.get("transcript_path"),
                                      payload.get("session_id"))
    out = []
    for op in ops:
        base = dict(payload)
        base["transcript_path"] = transcript
        if op["kind"] == "add":
            base["tool_name"] = "Write"
            base["tool_input"] = {
                "file_path": op["path"],
                "content": "\n".join(op["added"]),
            }
        else:
            # update and delete both land on Edit: an Edit payload carries both
            # the added and the removed text, and a delete simply has no added
            # text, which every guard treats as "nothing was written".
            base["tool_name"] = "Edit"
            base["tool_input"] = {
                "file_path": op["path"],
                "old_string": "\n".join(op["removed"]),
                "new_string": "\n".join(op["added"]),
            }
        out.append(base)
    return out


# --------------------------------------------------------------------------
# running the wrapped hook
# --------------------------------------------------------------------------


def run_wrapped(command, payload):
    try:
        proc = subprocess.run(
            command,
            shell=True,
            input=json.dumps(payload),
            capture_output=True,
            text=True,
        )
    except Exception as exc:  # noqa: BLE001 - a broken wrapped hook must fail open
        log("wrapped command raised: %r" % (exc,))
        return 0, "", ""
    return proc.returncode, proc.stdout or "", proc.stderr or ""


def is_denial(stdout):
    """True when the wrapped hook's JSON stdout is a deny/block."""
    for line in (stdout or "").splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            continue
        if not isinstance(obj, dict):
            continue
        if obj.get("decision") == "block":
            return True
        if obj.get("continue") is False:
            return True
        spec = obj.get("hookSpecificOutput")
        if isinstance(spec, dict) and spec.get("permissionDecision") == "deny":
            return True
    return False


def merge_stdout(chunks):
    """One stdout for N wrapped invocations.

    Codex reads a single JSON object; emitting three of them would be
    ambiguous. Merge the additionalContext strings when every chunk is a
    hookSpecificOutput object, otherwise fall back to concatenation.
    """
    chunks = [c for c in chunks if c and c.strip()]
    if not chunks:
        return ""
    if len(chunks) == 1:
        return chunks[0]
    objs = []
    for c in chunks:
        try:
            obj = json.loads(c.strip())
        except json.JSONDecodeError:
            return "\n".join(c.rstrip("\n") for c in chunks)
        if not isinstance(obj, dict) or "hookSpecificOutput" not in obj:
            return "\n".join(c.rstrip("\n") for c in chunks)
        objs.append(obj)
    merged = dict(objs[0])
    spec = dict(merged.get("hookSpecificOutput") or {})
    contexts = []
    for obj in objs:
        s = obj.get("hookSpecificOutput") or {}
        ctx = s.get("additionalContext")
        if isinstance(ctx, str) and ctx.strip() and ctx not in contexts:
            contexts.append(ctx)
    if contexts:
        spec["additionalContext"] = "\n".join(contexts)
    merged["hookSpecificOutput"] = spec
    return json.dumps(merged)


# --------------------------------------------------------------------------
# main
# --------------------------------------------------------------------------


def parse_args(argv):
    """-> wrapped shell command string."""
    if "--b64" in argv:
        i = argv.index("--b64")
        blob = argv[i + 1] if len(argv) > i + 1 else ""
        return base64.b64decode(blob).decode("utf-8")
    if "--" in argv:
        i = argv.index("--")
        return " ".join(argv[i + 1:])
    return ""


def main(argv, stdin_text):
    command = parse_args(argv)
    if not command:
        log("no wrapped command, nothing to do")
        return 0, "", ""

    if not stdin_text.strip():
        return run_wrapped(command, {})
    try:
        payload = json.loads(stdin_text)
    except json.JSONDecodeError:
        log("unparseable stdin, forwarding verbatim")
        rc = subprocess.run(command, shell=True, input=stdin_text,
                            capture_output=True, text=True)
        return rc.returncode, rc.stdout or "", rc.stderr or ""
    if not isinstance(payload, dict):
        return run_wrapped(command, payload)

    event = payload.get("hook_event_name")
    tool = payload.get("tool_name")

    if event == "Stop":
        payload = dict(payload)
        payload["transcript_path"] = translate_transcript(
            payload.get("transcript_path"),
            payload.get("session_id"),
            extra_assistant=payload.get("last_assistant_message"),
        )
        log("Stop: translated transcript -> %s" % payload["transcript_path"])
        return run_wrapped(command, payload)

    if event in ("PreToolUse", "PostToolUse") and tool == "apply_patch":
        payloads = synth_payloads(payload)
        if len(payloads) > MAX_FILES_PER_PATCH and event == "PostToolUse":
            # The write already landed, so refusing here protects nothing: it
            # only withholds formatting, the drift self-heal and the guards'
            # feedback. Check as many as the cap allows and say plainly which
            # files went unchecked.
            log("PostToolUse over cap: %d files, checking the first %d"
                % (len(payloads), MAX_FILES_PER_PATCH))
            sys.stderr.write(
                "codex-shim: this apply_patch touched %d files, over the "
                "%d-file cap. The first %d were checked by the PostToolUse "
                "guards; the rest were NOT. Treat the remainder as unchecked "
                "and split large patches.\n"
                % (len(payloads), MAX_FILES_PER_PATCH, MAX_FILES_PER_PATCH)
            )
            payloads = payloads[:MAX_FILES_PER_PATCH]
        elif len(payloads) > MAX_FILES_PER_PATCH:
            # Fail CLOSED. Silently guarding only the first N files of a big
            # patch is worse than refusing it: the guard looks alive and is not.
            log("DENY: patch touches %d files, over the %d cap"
                % (len(payloads), MAX_FILES_PER_PATCH))
            return 2, "", (
                "BLOCKED (codex-shim): this apply_patch touches %d files, over "
                "the %d-file cap this shim will guard in one call. Split it into "
                "smaller patches so every file gets checked. The cap exists so a "
                "runaway patch cannot fork hundreds of guard processes; it is "
                "deliberately a refusal rather than a partial check, because a "
                "guard that silently skips files is worse than no guard.\n"
                % (len(payloads), MAX_FILES_PER_PATCH)
            )
        if not payloads:
            log("apply_patch with an unparseable patch, forwarding verbatim")
            return run_wrapped(command, payload)
        log("apply_patch -> %d synthesized payload(s): %s"
            % (len(payloads), [p["tool_input"]["file_path"] for p in payloads]))
        outs = []
        for p in payloads:
            rc, out, err = run_wrapped(command, p)
            if rc == 2:
                log("DENY (exit 2) on %s" % p["tool_input"]["file_path"])
                return 2, out, err
            if is_denial(out):
                log("DENY (json) on %s" % p["tool_input"]["file_path"])
                return rc, out, err
            outs.append(out)
            if err.strip():
                sys.stderr.write(err)
        return 0, merge_stdout(outs), ""

    return run_wrapped(command, payload)


if __name__ == "__main__":
    try:
        code, out, err = main(sys.argv[1:], sys.stdin.read())
    except BaseException:  # noqa: BLE001 - a shim must never wedge a session
        code, out, err = 0, "", ""
    if out:
        sys.stdout.write(out)
    if err:
        sys.stderr.write(err)
    sys.exit(code if code in (0, 2) else 0)
