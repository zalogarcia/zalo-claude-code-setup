def command_description(meta, body):
    desc = (meta.get("description") or "").strip()
    if desc:
        return " ".join(desc.split())
    for para in re.split(r"\n\s*\n", body.strip()):
        para = para.strip()
        if not para or para.startswith(("#", "@", "```", "|", "-", "*")):
            continue
        return " ".join(para.split())
    return "Projected from a Claude Code slash command."


INCLUDE_RE = re.compile(r"^@(~?[/\w.\-]+\.md)\s*$", re.M)


def rewrite_command_body(body):
    body = INCLUDE_RE.sub(
        lambda m: "Read %s before proceeding (it is a rule file, not a reference; "
                  "its contents are load-bearing)." % m.group(1),
        body,
    )
    return body.replace("$ARGUMENTS", "the user's request text")


def gen_skills(s):
    claude_skills = os.path.join(CLAUDE, "skills")
    names = sorted(
        d for d in os.listdir(claude_skills)
        if os.path.isdir(os.path.join(claude_skills, d)) and d not in SKILL_DENYLIST
    ) if os.path.isdir(claude_skills) else []

    linked = kept = already = 0
    for name in names:
        src = os.path.join(claude_skills, name)
        dst = os.path.join(SKILLS_OUT, name)

        # Already one file tree. Eleven skills (mediabunny, the remotion set,
        # watch) live physically in ~/.agents/skills and are symlinked INTO
        # ~/.claude/skills, i.e. the reverse of the direction this generator
        # projects. Codex already sees them; linking them back would build a
        # loop and orphan the only copy of the content. Leave them alone.
        if os.path.lexists(dst) and os.path.realpath(src) == os.path.realpath(dst):
            already += 1
            continue

        if os.path.islink(dst):
            if s.symlink(dst, src):
                s.say("  relinked skill %s" % name)
            linked += 1
            continue

        if os.path.isdir(dst):
            # A real directory here is somebody else's data. Report it, never
            # replace it: "identical" is not a licence to delete.
            kept += 1
            diff = subprocess.run(["diff", "-rq", src, dst], capture_output=True, text=True)
            summary = ("identical content" if diff.returncode == 0
                       else " / ".join(diff.stdout.strip().splitlines()[:3]) or "differs")
            s.note("skills: %s already exists as a real directory, left untouched "
                   "(%s vs ~/.claude/skills/%s)" % (dst, summary, name))
            continue

        s.symlink(dst, src)
        linked += 1

    # slash commands become one-file skills
    cmd_dir = os.path.join(CLAUDE, "commands")
    cmds = sorted(f[:-3] for f in os.listdir(cmd_dir) if f.endswith(".md")) \
        if os.path.isdir(cmd_dir) else []
    generated = 0
    for cmd in cmds:
        if cmd in names:
            s.note("skills: command /%s collides with skill %s, command skipped" % (cmd, cmd))
            continue
        raw = read(os.path.join(cmd_dir, cmd + ".md"))
        meta, body = frontmatter(raw)
        desc = command_description(meta, body)
        out = os.path.join(SKILLS_OUT, cmd, "SKILL.md")
        content = (
            "---\n"
            "name: %s\n"
            "description: %s\n"
            "---\n\n"
            "<!--\n%s\n-->\n\n"
            "This skill is the Codex projection of the Claude Code slash command "
            "`/%s`. Invoke it as `$%s`.\n\n"
            "%s\n"
            % (cmd, json.dumps(desc),
               GENERATED_BANNER.format(sources="~/.claude/commands/%s.md" % cmd),
               cmd, cmd, rewrite_command_body(body).strip())
        )
        if s.write(out, content):
            s.say("  wrote command skill %s" % cmd)
        generated += 1

    removed = prune_orphan_skills(s, set(names), set(cmds))
    s.say("  skills: %d symlinked, %d already unified, %d real dirs kept, "
          "%d command skills, %d orphans removed"
          % (linked, already, kept, generated, removed))
    return linked + already + generated


def prune_orphan_skills(s, skill_names, command_names):
    """Delete projections whose source is gone. Deletions must propagate too.

    Without this, renaming a command leaves Codex offering the OLD one with a
    stale body, and `check` still reports "in sync" because it only ever looks
    at sources that still exist. Only two shapes are ever removed, both of
    which this generator created:
      - a symlink pointing into ~/.claude/skills whose target no longer exists
      - a directory holding nothing but a SKILL.md carrying our banner, whose
        source command file is gone
    Anything else is somebody else's data and is left alone.
    """
    if not os.path.isdir(SKILLS_OUT):
        return 0
    claude_skills = os.path.realpath(os.path.join(CLAUDE, "skills"))
    cmd_dir = os.path.join(CLAUDE, "commands")
    removed = 0
    for name in sorted(os.listdir(SKILLS_OUT)):
        path = os.path.join(SKILLS_OUT, name)

        if os.path.islink(path):
            target = os.path.realpath(path)
            if not target.startswith(claude_skills + os.sep):
                continue  # not ours
            if name in skill_names and os.path.exists(target):
                continue
            s.remove(path)
            s.say("  removed orphaned skill symlink %s" % name)
            removed += 1
            continue

        if not os.path.isdir(path):
            continue

        # A REVERSE ORIGINAL: ~/.claude/skills/<name> is a symlink pointing AT
        # this directory, so this is the only physical copy of a real skill
        # (mediabunny, the remotion set, watch). Never a projection, never
        # ours to delete. This exact shape already cost 11 skill directories
        # once; a single stray mention of this script's name inside a
        # SKILL.md must not be enough to lose one.
        claude_side = os.path.join(claude_skills, name)
        if os.path.islink(claude_side) and os.path.realpath(claude_side) == os.path.realpath(path):
            continue

        if name in command_names and os.path.isfile(
                os.path.join(cmd_dir, name + ".md")):
            continue
        entries = os.listdir(path)
        if entries != ["SKILL.md"]:
            continue  # a real skill directory, never ours to delete
        if "codex-sync.py" not in read(os.path.join(path, "SKILL.md")):
            continue  # not generated by us
        s.remove(os.path.join(path, "SKILL.md"))
        if not s.dry:
            try:
                os.rmdir(path)  # only ever succeeds on an EMPTY directory
            except OSError:
                pass
        s.say("  removed orphaned command skill %s" % name)
        removed += 1
    return removed


