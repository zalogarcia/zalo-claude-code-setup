def gen_agents_md(s):
    bodies = []
    names = []
    for label, path in AGENTS_MD_SOURCES:
        body = read(path)
        if not body.strip():
            s.note("agents-md: source missing or empty, skipped: %s" % path)
            continue
        names.append(label)
        bodies.append(body.rstrip("\n"))

    concatenated = "\n\n".join(bodies)
    digest = hashlib.sha256(concatenated.encode("utf-8")).hexdigest()[:12]

    header = [
        "<!--",
        GENERATED_BANNER.format(sources=", ".join(names)),
        "-->",
        "",
    ]
    tail = [
        "",
        "---",
        "",
        "%s: %s" % (SENTINEL_KEY, digest),
        "",
    ]
    content = "\n".join(header) + concatenated + "\n" + "\n".join(tail)
    if s.write(AGENTS_MD_OUT, content):
        s.say("  wrote %s (%d bytes, sentinel %s)" % (AGENTS_MD_OUT, len(content), digest))
    return digest


