PROJECT_DOC_MAX_BYTES = 262144

# Some vendors route MCP by client family in the URL path. leadconnector
# answers a Codex client on /mcp/anthropic/v2 with
#   HTTP 400 client_path_mismatch: This MCP client must use /mcp/openai/v2
# so the Claude URL cannot be copied across verbatim. Measured 2026-09-04.
URL_REWRITES = (
    ("services.leadconnectorhq.com/mcp/anthropic/", "/mcp/anthropic/", "/mcp/openai/"),
)


def codex_url(url):
    for host_marker, old, new in URL_REWRITES:
        if host_marker in url:
            return url.replace(old, new)
    return url



def gen_mcp(s):
    try:
        cfg = json.loads(read(CLAUDE_JSON, "{}"))
    except json.JSONDecodeError:
        s.note("mcp: ~/.claude.json does not parse, config block untouched")
        return False
    servers = cfg.get("mcpServers") or {}

    lines = [
        BEGIN,
        "# Regenerate with: python3 ~/.claude/scripts/codex-sync.py mcp",
        "# Source: ~/.claude.json mcpServers. Everything outside this block is "
        "preserved byte for byte.",
        "",
        "project_doc_max_bytes = %d" % PROJECT_DOC_MAX_BYTES,
        "",
    ]
    for name in sorted(servers):
        spec = servers[name] or {}
        head = "[mcp_servers.%s]" % toml_key(name)
        lines.append(head)
        url = spec.get("url")
        if url:
            lines.append("url = %s" % toml_str(codex_url(url)))
        else:
            if spec.get("command"):
                lines.append("command = %s" % toml_str(spec["command"]))
            args = spec.get("args") or []
            if args:
                lines.append("args = [%s]" % ", ".join(toml_str(a) for a in args))
        # Claude's per-server `timeout` is milliseconds; Codex wants seconds.
        t = spec.get("timeout")
        if isinstance(t, int) and t > 0:
            lines.append("tool_timeout_sec = %d" % max(1, round(t / 1000)))
        env = spec.get("env") or {}
        if env:
            lines.append("")
            lines.append("[mcp_servers.%s.env]" % toml_key(name))
            for k in sorted(env):
                lines.append("%s = %s" % (toml_key(k), toml_str(str(env[k]))))
        lines.append("")
    lines.append(END)
    block = "\n".join(lines) + "\n"

    existing = read(CONFIG_OUT, "")
    new = splice_block(existing, block)
    changed = s.write(CONFIG_OUT, new, mode=0o600)
    if changed:
        s.say("  wrote managed block in %s (%d mcp servers)" % (CONFIG_OUT, len(servers)))
    return changed


def splice_block(existing, block):
    """Replace the managed block, preserving every other line byte for byte.

    The block carries root-level keys, so it must sit above the first table
    header or TOML would read those keys as belonging to that table. Any root
    keys the file already had before its first table stay above the block.
    """
    lines = existing.splitlines(keepends=True)
    start = end = None
    for i, line in enumerate(lines):
        if line.strip() == BEGIN and start is None:
            start = i
        elif line.strip() == END and start is not None:
            end = i
            break
    if start is not None and end is not None:
        return "".join(lines[:start]) + block + "".join(lines[end + 1:])

    leading, rest = [], lines
    for i, line in enumerate(lines):
        if line.lstrip().startswith("["):
            leading, rest = lines[:i], lines[i:]
            break
    else:
        leading, rest = lines, []
    head = "".join(leading)
    if head and not head.endswith("\n"):
        head += "\n"
    if head.strip():
        head += "\n"
    return head + block + "\n" + "".join(rest)


