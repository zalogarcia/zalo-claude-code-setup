def wrap_in_shim(command):
    """Route a Claude Edit/Write/MultiEdit or Stop hook through the shim.

    Plain `-- <cmd>` where the command is shell-safe, base64 where it is not:
    the hooks.json string is handed to a shell, which would otherwise expand a
    wrapped one-liner's $(...) before the shim ever ran.
    """
    if re.fullmatch(r"[\w./~ \-]+", command or ""):
        return "python3 %s -- %s" % (SHIM, command)
    blob = base64.b64encode(command.encode("utf-8")).decode("ascii")
    return "python3 %s --b64 %s" % (SHIM, blob)


def clamp(timeout):
    if not isinstance(timeout, int):
        return None
    return min(timeout, MAX_HOOK_TIMEOUT)


def gen_hooks(s):
    try:
        settings = json.loads(read(SETTINGS, "{}"))
    except json.JSONDecodeError:
        s.note("hooks: ~/.claude/settings.json does not parse, hooks.json untouched")
        return False
    src = settings.get("hooks") or {}
    out = {}
    dropped = []

    def add(event, entry):
        out.setdefault(event, []).append(entry)

    def hook_entries(hooks, transform=None):
        res = []
        for h in hooks or []:
            if h.get("type") != "command" or not h.get("command"):
                continue
            cmd = h["command"]
            if transform:
                cmd = transform(cmd)
            item = {"type": "command", "command": cmd}
            t = clamp(h.get("timeout"))
            if t is not None:
                item["timeout"] = t
            res.append(item)
        return res

    for event in ("PreToolUse", "PostToolUse"):
        for entry in src.get(event) or []:
            matcher = entry.get("matcher") or ""
            tools = [t for t in matcher.split("|") if t]
            keep = [t for t in tools if t not in PATCH_TOOLS and t not in AGENT_TOOLS]
            patchy = [t for t in tools if t in PATCH_TOOLS]
            agenty = [t for t in tools if t in AGENT_TOOLS]

            if keep:
                add(event, {"matcher": "|".join(keep), "hooks": hook_entries(entry["hooks"])})
            if patchy:
                add(event, {"matcher": "apply_patch",
                            "hooks": hook_entries(entry["hooks"], wrap_in_shim)})
            if agenty and not keep and not patchy:
                for h in entry.get("hooks") or []:
                    dropped.append("%s %s -> %s" % (event, matcher, h.get("command", "")))

    # SessionStart: session-start.sh is deliberately NOT ported. It injects
    # META_RULE.md as additionalContext, and Codex caps that at 2500 chars,
    # which would truncate an 8 KB rule file into nonsense. META_RULE.md is
    # folded into AGENTS.md instead. The slot is reused to self-heal drift.
    add("SessionStart", {
        "matcher": ".*",
        "hooks": [{
            "type": "command",
            "command": "python3 %s all --if-stale --quiet"
                       % os.path.join(CLAUDE, "scripts", "codex-sync.py"),
            "timeout": 60,
        }],
    })

    for event in ("PreCompact", "UserPromptSubmit"):
        for entry in src.get(event) or []:
            add(event, {"hooks": hook_entries(entry["hooks"])})

    # Stop reads the last assistant turn out of the transcript, and a Codex
    # rollout is not a Claude transcript, so it goes through the shim's
    # translation path.
    for entry in src.get("Stop") or []:
        add("Stop", {"hooks": hook_entries(entry["hooks"], wrap_in_shim)})

    content = json.dumps({"hooks": out}, indent=2) + "\n"
    changed = s.write(HOOKS_OUT, content)
    if changed:
        s.hooks_changed = True
        s.say("  wrote %s" % HOOKS_OUT)
    for d in dropped:
        s.note("hooks: NOT ported (no Codex equivalent that the guard can use): %s" % d)
    return changed


