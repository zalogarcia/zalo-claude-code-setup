READ_ONLY_TOOLSETS = {"read", "grep", "glob", "bash"}

# The Claude tool lists cannot separate "reports a verdict" from "drives a dev
# server and a browser": brainstorm, bug-fix, live-test, outcomes-grader,
# qa-agent and safe-planner all declare exactly `Read, Grep, Glob, Bash`. In
# Claude a Bash grant can write; a Codex read-only sandbox cannot, so the two
# agents whose job is to RUN things would fail on their first mkdir or
# `npm run dev`. Name them explicitly.
SANDBOX_OVERRIDES = {
    "live-test": "workspace-write",   # starts servers, drives a browser, saves screenshots
    "bug-fix": "workspace-write",     # reproduces the bug, which means running the code
}


def gen_agents(s):
    src_dir = os.path.join(CLAUDE, "agents")
    if not os.path.isdir(src_dir):
        return 0
    written = 0
    seen = set()
    for fn in sorted(os.listdir(src_dir)):
        if not fn.endswith(".md"):
            continue
        meta, body = frontmatter(read(os.path.join(src_dir, fn)))
        name = meta.get("name") or fn[:-3]
        seen.add(name + ".toml")
        desc = " ".join((meta.get("description") or name).split())
        model, effort = MODEL_MAP.get((meta.get("model") or "").strip(), DEFAULT_MODEL)

        tools_raw = (meta.get("tools") or "").strip()
        tools = [t.strip() for t in tools_raw.split(",") if t.strip()]
        read_only = bool(tools) and all(t.lower() in READ_ONLY_TOOLSETS for t in tools)
        sandbox = SANDBOX_OVERRIDES.get(
            name, "read-only" if read_only else "workspace-write")
        read_only = sandbox == "read-only"

        guidance = [body.rstrip()]
        guidance.append("\n## Tools (Codex)\n")
        if tools:
            guidance.append(
                "The Claude definition of this agent granted exactly these tools: "
                "%s. Codex has no per-agent tool allowlist, so treat that list as "
                "a boundary you keep yourself." % ", ".join(tools)
            )
        else:
            guidance.append(
                "The Claude definition of this agent granted all tools. Use what "
                "the task needs and nothing more."
            )
        if read_only:
            guidance.append(
                "\nThis agent runs read-only: you cannot write files, and you are "
                "not supposed to. Report findings; the orchestrator applies them."
            )
        guidance.append(
            "\nTranslations: `Edit`/`Write`/`MultiEdit` is `apply_patch`; the "
            "`Agent` tool is `spawn_agent`; `ToolSearch` is unnecessary because "
            "MCP tools are preloaded; `@~/.claude/rules/x.md` means read that "
            "file before proceeding."
        )

        lines = [
            "# %s" % GENERATED_BANNER.format(
                sources="~/.claude/agents/%s" % fn).replace("\n", "\n# "),
            "",
            "name = %s" % toml_str(name),
            "description = %s" % toml_str(desc),
            "model = %s" % toml_str(model),
            "model_reasoning_effort = %s" % toml_str(effort),
            "sandbox_mode = %s" % toml_str(sandbox),
            "developer_instructions = %s" % toml_multiline("\n".join(guidance) + "\n"),
            "",
        ]
        if s.write(os.path.join(AGENTS_DIR_OUT, name + ".toml"), "\n".join(lines)):
            s.say("  wrote agent %s (%s, %s, %s)" % (name, model, effort, sandbox))
        written += 1

    # A renamed or deleted Claude agent must not leave a ghost behind, but only
    # remove files this generator recognises as its own.
    if os.path.isdir(AGENTS_DIR_OUT):
        for fn in sorted(os.listdir(AGENTS_DIR_OUT)):
            if not fn.endswith(".toml") or fn in seen:
                continue
            if "codex-sync.py" in read(os.path.join(AGENTS_DIR_OUT, fn)):
                s.remove(os.path.join(AGENTS_DIR_OUT, fn))
                s.say("  removed stale agent %s" % fn)
    return written


