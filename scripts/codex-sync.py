class Sync:
    def __init__(self, dry=False, quiet=False):
        self.dry = dry
        self.quiet = quiet
        self.changed = []
        self.notes = []
        self.hooks_changed = False

    def say(self, msg):
        if not self.quiet:
            print(msg)

    def note(self, msg):
        self.notes.append(msg)

    def write(self, path, content, mode=None):
        old = None
        if os.path.exists(path) and not os.path.islink(path):
            try:
                with open(path, encoding="utf-8") as f:
                    old = f.read()
            except OSError:
                old = None
        if old == content:
            if mode is not None and not self.dry:
                try:
                    os.chmod(path, mode)
                except OSError:
                    pass
            return False
        self.changed.append(path)
        if self.dry:
            return True
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp.%d" % os.getpid()
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(content)
        if mode is not None:
            os.chmod(tmp, mode)
        os.replace(tmp, path)
        return True

    def symlink(self, link, target):
        if os.path.islink(link) and os.path.realpath(link) == os.path.realpath(target):
            return False
        self.changed.append(link)
        if self.dry:
            return True
        os.makedirs(os.path.dirname(link), exist_ok=True)
        subprocess.run(["ln", "-sfn", target, link], check=False)
        return True

    def remove(self, path):
        """Unlink a symlink or a file. NEVER recursively delete a directory.

        This generator owns symlinks and generated files, nothing else. It once
        rm -rf'd 11 real skill directories that turned out to be the ORIGINALS
        (~/.claude/skills held symlinks pointing INTO ~/.agents/skills, not
        copies of it), and the content was only recoverable from upstream.
        A projection tool has no business deleting a directory tree.
        """
        if not os.path.lexists(path):
            return False
        if os.path.isdir(path) and not os.path.islink(path):
            self.note("refused to delete the real directory %s (this tool only "
                      "removes symlinks and files it generated)" % path)
            return False
        self.changed.append(path)
        if self.dry:
            return True
        os.unlink(path)
        return True


def read(path, default=""):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        return default


def frontmatter(text):
    """-> (dict of top-level scalar keys, body). Nested YAML blocks are skipped."""
    if not text.startswith("---"):
        return {}, text
    parts = text.split("\n", 1)
    if len(parts) < 2 or parts[0].strip() != "---":
        return {}, text
    rest = parts[1]
    end = rest.find("\n---")
    if end == -1:
        return {}, text
    head = rest[:end]
    body = rest[end + 4:]
    if body.startswith("\n"):
        body = body[1:]
    meta = {}
    for line in head.splitlines():
        if not line.strip() or line.startswith((" ", "\t", "#", "-")):
            continue
        if ":" not in line:
            continue
        k, _, v = line.partition(":")
        v = v.strip()
        if v.startswith("'") and v.endswith("'") and len(v) > 1:
            v = v[1:-1].replace("''", "'")
        elif v.startswith('"') and v.endswith('"') and len(v) > 1:
            v = v[1:-1]
        meta[k.strip()] = v
    return meta, body


def toml_str(s):
    """A TOML basic string."""
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    out = "".join(c if ord(c) >= 0x20 or c in "\n\t" else "\\u%04x" % ord(c) for c in out)
    return '"%s"' % out


def toml_key(k):
    return k if re.fullmatch(r"[A-Za-z0-9_-]+", k or "") else toml_str(k)


def toml_multiline(s):
    """A TOML multiline string, literal where possible so backslashes survive."""
    if "'''" not in s and not s.endswith("'"):
        return "'''\n" + s + "'''"
    esc = s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return '"""\n' + esc + '"""'


