#!/usr/bin/env python3
"""Project the Claude Code setup in ~/.claude into Codex CLI's ~/.codex.

ONE source of truth. ~/.claude is it. Everything this script writes under
~/.codex and ~/.agents is generated and disposable: edit the source, re-run,
never hand-edit the projection.

What it generates
-----------------
  agents-md  ~/.codex/AGENTS.md          from codex/AGENTS.delta.md + META_RULE.md
                                         + ~/.claude/CLAUDE.md + ~/dev/CLAUDE.md
  skills     ~/.agents/skills/*          symlinks to ~/.claude/skills/*, plus a
                                         generated SKILL.md per slash command
  hooks      ~/.codex/hooks.json         from ~/.claude/settings.json, with the
                                         Edit/Write/MultiEdit hooks rerouted
                                         through hooks/codex-shim.py
  agents     ~/.codex/agents/*.toml      from ~/.claude/agents/*.md
  mcp        ~/.codex/config.toml        a sentinel-delimited managed block:
                                         project_doc_max_bytes + [mcp_servers.*]

Usage
-----
  codex-sync.py all              regenerate everything
  codex-sync.py check            report drift, write nothing, exit 1 if stale
  codex-sync.py agents-md|skills|hooks|agents|mcp
  codex-sync.py all --if-stale --quiet     the SessionStart self-heal shape
  codex-sync.py --on-edit        reads a Claude PostToolUse payload on stdin and
                                 regenerates only what that file feeds

Idempotent by construction: every write goes through write_if_changed, so a
second run reports zero changes.
"""

