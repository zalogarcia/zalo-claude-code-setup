def run_targets(targets, dry=False, quiet=False):
    s = Sync(dry=dry, quiet=quiet)
    for name in targets:
        s.say("%s:" % name)
        TARGETS[name](s)
    return s


def report(s, quiet):
    if s.notes and not quiet:
        print("\nnotes:")
        for n in s.notes:
            print("  - %s" % n)
    if not quiet:
        print("\n%d file(s) changed." % len(s.changed))
    if s.hooks_changed:
        print(HOOKS_RETRUST_WARNING, file=sys.stderr)


def on_edit(argv):
    """PostToolUse entry point: regenerate only what the edited file feeds."""
    try:
        payload = json.loads(sys.stdin.read() or "{}")
    except json.JSONDecodeError:
        return 0
    path = ((payload.get("tool_input") or {}).get("file_path") or "").strip()
    if not path:
        return 0
    real = os.path.realpath(os.path.expanduser(path))
    targets = list(WATCHED_EXACT.get(real) or [])
    if not targets:
        for d, suffix, t in WATCHED_DIRS:
            if real.startswith(os.path.realpath(d) + os.sep) and real.endswith(suffix):
                targets = list(t)
                break
    if not targets:
        return 0
    s = run_targets([t for t in ORDER if t in targets], quiet=True)
    if not s.changed:
        return 0
    print("codex-sync: regenerated %s after an edit to %s"
          % (", ".join(targets), path), file=sys.stderr)
    if s.hooks_changed:
        # Exit 2 on purpose. Codex binds hook trust to the hooks.json hash, so
        # this rewrite just turned EVERY mirrored guard off over there. A
        # PostToolUse hook that exits 0 does not surface its stderr, so a quiet
        # return here would disarm gitleaks, money-guard, npm-install-guard and
        # the rest without anyone being told.
        print(HOOKS_RETRUST_WARNING, file=sys.stderr)
        return 2
    return 0


def main(argv):
    quiet = "--quiet" in argv
    if_stale = "--if-stale" in argv
    if "--on-edit" in argv:
        return on_edit(argv)

    positional = [a for a in argv if not a.startswith("-")]
    cmd = positional[0] if positional else "all"

    if cmd == "check":
        s = run_targets(ORDER, dry=True, quiet=True)
        if s.changed:
            print("STALE: %d projected file(s) differ from the source." % len(s.changed))
            for p in s.changed:
                print("  %s" % p)
            return 1
        print("in sync")
        return 0

    if cmd == "all":
        targets = ORDER
    elif cmd in TARGETS:
        targets = [cmd]
    else:
        print(__doc__)
        return 2

    if if_stale:
        pre = run_targets(targets, dry=True, quiet=True)
        if not pre.changed:
            return 0
    s = run_targets(targets, quiet=quiet)
    report(s, quiet)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
