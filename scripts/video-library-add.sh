#!/bin/bash
# video-library-add.sh: put one finished, postable video into the library at ~/dev/videos
# and insert or update its row in the README index.
#
#   video-library-add.sh <brand> <type> "<YYYY-MM-DD> <slug>" <video> [options]
#   video-library-add.sh --render            # rebuild the README index block from .index.tsv
#   video-library-add.sh --set-status "<brand>/<type>/<YYYY-MM-DD> <slug>" posted:<platform>:<date>
#                                            # mark a video posted (or ready, unknown): changes the
#                                            # row's status only, clones nothing, touches no file
#
# Options (repeatable where it makes sense):
#   --video <file>      another cut of the same video (headline variant, other aspect)
#   --cover <file>      cover or thumbnail; youtube goes to thumbnails/, others to cover-N.<ext>
#   --text <file>       copy-paste text (caption, headlines, titles, description), kept by name;
#                       --text caption.txt=<file> clones <file> under the name caption.txt
#                       (<file> may be relative; a leading ~/ is expanded)
#   --status <s>        ready | unknown | posted:<platform>:<YYYY-MM-DD>   (default ready)
#   --what "<text>"     what it is, one line (kept from the existing row when omitted)
#
# Files are CLONED with cp -c (APFS clonefile: no extra disk space, an independent file, so
# deleting the original never deletes the library copy). Nothing is ever copied in full:
# cp -c silently falls back to a full copy across volumes, so the script refuses before that
# can happen (a source on another volume, or an iCloud-evicted source, exits 3, nothing
# written). Symlinks are resolved first, so those checks see the real file, and the Source
# column holds its absolute path. Originals are only read. Running it again for the same
# folder updates the row and replaces the clones; it never adds a second row, and cuts from
# an earlier run that are still in the folder stay listed.
#
# Library root: $VIDEO_LIBRARY_DIR (default ~/dev/videos). The index lives in
# <root>/.index.tsv (one row per video folder); the README block between the INDEX markers
# is generated from it, everything outside the markers is left as written.
# Exit codes: 0 ok, 2 usage or missing file, 3 cannot clone (volume, iCloud, clone error).
set -u
LIB="${VIDEO_LIBRARY_DIR:-$HOME/dev/videos}"
BRANDS="zalo-kabche black-umbrella delta-agents operator-base cmaa leash"

die() { echo "video-library-add: $2" >&2; exit "$1"; }

render() {
  python3 - "$LIB" <<'PY'
import os, sys, re
lib = sys.argv[1]
idx = os.path.join(lib, '.index.tsv')
readme = os.path.join(lib, 'README.md')
BRANDS = ['zalo-kabche', 'black-umbrella', 'delta-agents', 'operator-base', 'cmaa', 'leash']
COLS = ['folder', 'brand', 'type', 'what', 'length', 'aspect', 'status', 'source', 'copy', 'videos']
rows = []
if os.path.exists(idx):
    lines = open(idx, encoding='utf-8').read().split('\n')
    head = lines[0].split('\t') if lines else COLS
    rows = [dict(zip(head, l.split('\t'))) for l in lines[1:] if l.strip()]
def cell(s):
    s = (s or '').replace('|', '/').replace('\n', ' ').strip()
    # the owner's copy has no em or en dashes; in a path the dash becomes a * glob
    return s.replace('\u2014', '*').replace('\u2013', '*')
def status_cell(s):
    if s.startswith('posted:'):
        p = s.split(':')
        return 'posted %s %s' % (p[1], p[2] if len(p) > 2 else '')
    return s
def link(folder):
    return '[%s](<%s/>)' % (folder, folder)
HDR = '| Folder | What it is | Length | Aspect | Status | Source | Copy |\n|---|---|---|---|---|---|---|'
def line(r):
    return '| %s | %s | %s | %s | %s | %s | %s |' % (link(cell(r['folder'])), cell(r['what']), cell(r['length']),
        cell(r['aspect']), cell(status_cell(r['status'])), cell(r['source']), cell(r['copy']))
def order(r):  # newest first inside every table
    m = re.search(r'/(\d{4}-\d{2}-\d{2}) ', r['folder'])
    return m.group(1) if m else ''
out = ['<!-- INDEX:BEGIN generated by ~/.claude/scripts/video-library-add.sh from .index.tsv; do not edit by hand -->', '']
ready = sorted([r for r in rows if r['status'] == 'ready'], key=order, reverse=True)
posted = [r for r in rows if r['status'].startswith('posted:')]
unknown = [r for r in rows if r['status'] == 'unknown']
out.append('%d video folders in the library: %d ready to post, %d posted, %d unknown.' % (len(rows), len(ready), len(posted), len(unknown)))
out.append('')
out.append('## Ready to post (%d)' % len(ready))
out.append('')
out.append(HDR)
out += [line(r) for r in ready]
out.append('')
out.append('## All videos by brand')
out.append('')
out.append('One table per brand: ready first, then posted, then unknown, newest first inside each group.')
for b in BRANDS + sorted(set(r['brand'] for r in rows) - set(BRANDS)):
    br = [r for r in rows if r['brand'] == b]
    if not br: continue
    out.append('')
    out.append('### %s (%d)' % (b, len(br)))
    out.append('')
    out.append(HDR)
    grp = {'ready': 0, 'posted': 1, 'unknown': 2}
    br.sort(key=order, reverse=True)
    br.sort(key=lambda r: grp.get(r['status'].split(':')[0], 3))
    out += [line(r) for r in br]
out.append('')
out.append('<!-- INDEX:END -->')
block = '\n'.join(out)
DEFAULT_HEAD = '# Videos\n\nEvery finished, postable video, one folder per video, sorted by brand and type.\n\n'
if os.path.exists(readme):
    text = open(readme, encoding='utf-8').read()
else:
    text = DEFAULT_HEAD
b = text.find('<!-- INDEX:BEGIN')
e = text.find('<!-- INDEX:END -->')
if b >= 0 and e > b:
    text = text[:b] + block + text[e + len('<!-- INDEX:END -->'):]
else:
    text = text.rstrip('\n') + '\n\n' + block + '\n'
tmp = readme + '.tmp'
open(tmp, 'w', encoding='utf-8').write(text)
os.replace(tmp, readme)
PY
}

if [ "${1:-}" = "--render" ]; then
  mkdir -p "$LIB" && render; exit $?
fi

if [ "${1:-}" = "--set-status" ]; then
  # change one row's status and nothing else: no clone, no probe, the folder is not touched
  [ $# -eq 3 ] || die 2 "usage: video-library-add.sh --set-status \"<brand>/<type>/<YYYY-MM-DD> <slug>\" <ready|unknown|posted:<platform>:<YYYY-MM-DD>>"
  [[ "$3" =~ ^(ready|unknown|posted:[a-z0-9.-]+:[0-9]{4}-[0-9]{2}-[0-9]{2})$ ]] || die 2 "status must be ready, unknown or posted:<platform>:<YYYY-MM-DD>, got '$3'"
  python3 - "$LIB" "$2" "$3" <<'PY' || exit $?
import os, sys
lib, rel, status = sys.argv[1:4]
rel = rel.rstrip('/')
if rel.startswith(lib.rstrip('/') + '/'): rel = rel[len(lib.rstrip('/')) + 1:]
idx = os.path.join(lib, '.index.tsv')
if not os.path.exists(idx):
    sys.stderr.write('video-library-add: no index at %s\n' % idx); sys.exit(2)
lines = open(idx, encoding='utf-8').read().split('\n')
si = lines[0].split('\t').index('status')
hit = 0
for i in range(1, len(lines)):
    f = lines[i].split('\t')
    if lines[i].strip() and f[0] == rel:
        f[si] = status; lines[i] = '\t'.join(f); hit += 1
if not hit:
    sys.stderr.write("video-library-add: no row for '%s' in the index\n" % rel); sys.exit(2)
tmp = idx + '.tmp'
open(tmp, 'w', encoding='utf-8').write('\n'.join(lines))
os.replace(tmp, idx)
print('status %s: %s' % (rel, status))
PY
  render || die 3 "README render failed"; exit 0
fi

[ $# -ge 4 ] || die 2 "usage: video-library-add.sh <brand> <type> \"<YYYY-MM-DD> <slug>\" <video> [--video f] [--cover f] [--text f] [--status s] [--what text]  |  --set-status <folder> <status>  |  --render"
BRAND="$1"; TYPE="$2"; NAME="$3"; VIDEO="$4"; shift 4
case " $BRANDS " in *" $BRAND "*) ;; *) die 2 "unknown brand '$BRAND' (allowed: $BRANDS)";; esac
[[ "$TYPE" =~ ^[a-z0-9][a-z0-9-]*$ ]] || die 2 "type must be lowercase words joined by hyphens, got '$TYPE'"
[[ "$NAME" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}\ [^/[:cntrl:]]+$ ]] || die 2 "folder name must be \"YYYY-MM-DD slug\" with no slash, got '$NAME'"

VIDEOS=("$VIDEO"); COVERS=(); TEXTS=(); STATUS="ready"; WHAT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --video) [ $# -ge 2 ] || die 2 "--video needs a file"; VIDEOS+=("$2"); shift 2;;
    --cover) [ $# -ge 2 ] || die 2 "--cover needs a file"; COVERS+=("$2"); shift 2;;
    --text)  [ $# -ge 2 ] || die 2 "--text needs a file"; TEXTS+=("$2"); shift 2;;
    --status) [ $# -ge 2 ] || die 2 "--status needs a value"; STATUS="$2"; shift 2;;
    --what) [ $# -ge 2 ] || die 2 "--what needs text"; WHAT="$2"; shift 2;;
    *) die 2 "unknown option '$1'";;
  esac
done
[[ "$STATUS" =~ ^(ready|unknown|posted:[a-z0-9.-]+:[0-9]{4}-[0-9]{2}-[0-9]{2})$ ]] || die 2 "status must be ready, unknown or posted:<platform>:<YYYY-MM-DD>, got '$STATUS'"
[[ "$WHAT" == *$'\t'* || "$WHAT" == *$'\n'* ]] && die 2 "--what must be one line with no tab"

mkdir -p "$LIB" || die 3 "cannot create $LIB"
LIBDEV=$(stat -L -f %d "$LIB")   # -L: a library root that is a symlink counts as the volume it points to
# Every source is checked, and resolved to its real absolute path, before anything is written.
# The checks run on the resolved file, the one cp -c reads, so a symlink to another volume or
# to an evicted iCloud file cannot slip past them.
real_src() { # real_src <path>: print the real absolute path of a file cp -c can clone, or die
  local r
  [ -f "$1" ] || die 2 "missing file: $1"
  r="$(/bin/realpath "$1" 2>/dev/null)" || die 2 "cannot resolve $1"
  [ "$(stat -f %d "$r")" = "$LIBDEV" ] || die 3 "$1 is on another volume than $LIB; cp -c would make a full copy there, refusing"
  case "$(stat -f %Sf "$r")" in *dataless*) die 3 "$1 is evicted to iCloud; run: brctl download \"$(dirname "$r")\" (the folder form; the per-file form can leave it unreadable), wait until it is local, then re-run";; esac
  printf '%s' "$r"
}
ext() { local e="${1##*.}"; [ "$e" = "$1" ] && echo "" || echo ".$(printf '%s' "$e" | tr 'A-Z' 'a-z')"; }
BASE="final"; [ "$TYPE" = "reels" ] && BASE="reel"
SV=(); VNAMES=(); SC=(); CNAMES=(); ST=(); TNAMES=()
n=0
for v in "${VIDEOS[@]}"; do
  n=$((n+1)); r=$(real_src "$v") || exit $?; SV+=("$r")
  if [ $n -eq 1 ]; then VNAMES+=("$BASE$(ext "$v")"); else VNAMES+=("$BASE-$n$(ext "$v")"); fi
done
n=0
for c in ${COVERS[@]+"${COVERS[@]}"}; do
  n=$((n+1)); r=$(real_src "$c") || exit $?; SC+=("$r")
  if [ "$TYPE" = "youtube" ]; then CNAMES+=("thumbnails/$(basename "$c")"); else CNAMES+=("cover-$n$(ext "$c")"); fi
done
for t in ${TEXTS[@]+"${TEXTS[@]}"}; do
  # name=<file> renames; the name has no slash, and a token that is itself a file stays a plain path
  if [ ! -e "$t" ] && [[ "$t" == *=* && "${t%%=*}" != */* && -n "${t%%=*}" ]]; then d="${t%%=*}"; f="${t#*=}"; else d=""; f="$t"; fi
  case "$f" in "~/"*) f="$HOME/${f#\~/}";; esac
  [ -n "$d" ] || d="$(basename "$f")"
  [[ "$d" == .* ]] && die 2 "text name must be a plain file name, got '$d'"
  r=$(real_src "$f") || exit $?; ST+=("$r"); TNAMES+=("$d")
done
DUP=$(printf '%s\n' "${VNAMES[@]}" ${CNAMES[@]+"${CNAMES[@]}"} ${TNAMES[@]+"${TNAMES[@]}"} | sort | uniq -d | head -1)
[ -z "$DUP" ] || die 2 "two files would land as '$DUP' in the same folder; rename one first"

DIR="$LIB/$BRAND/$TYPE/$NAME"
REL="$BRAND/$TYPE/$NAME"
mkdir -p "$DIR" || die 3 "cannot create $DIR"
clone() { # clone <src> <dest>: clone to a temp name in the folder, then rename over the old clone
  local tmp; tmp="$(dirname "$2")/.vla-tmp-$$-$(basename "$2")"
  mkdir -p "$(dirname "$2")"
  rm -f "$tmp"
  if ! cp -c -p "$1" "$tmp" 2>/dev/null; then rm -f "$tmp"; die 3 "cp -c failed for $1"; fi
  mv -f "$tmp" "$2" || die 3 "cannot place $2"
}
i=0; for d in "${VNAMES[@]}"; do clone "${SV[$i]}" "$DIR/$d"; i=$((i+1)); done
i=0; for d in ${CNAMES[@]+"${CNAMES[@]}"}; do clone "${SC[$i]}" "$DIR/$d"; i=$((i+1)); done
i=0; for d in ${TNAMES[@]+"${TNAMES[@]}"}; do clone "${ST[$i]}" "$DIR/$d"; i=$((i+1)); done

# a re-run with fewer cuts (say a status-only update) keeps listing the earlier cuts still in the folder
OLDV=$(F="$REL" awk -F'\t' 'NR>1 && $1==ENVIRON["F"] {print $10}' "$LIB/.index.tsv" 2>/dev/null)
if [ -n "$OLDV" ]; then
  IFS=';' read -r -a OLDA <<< "$OLDV"
  for o in "${OLDA[@]}"; do
    seen=0; for d in "${VNAMES[@]}"; do [ "$d" = "$o" ] && seen=1; done
    [ $seen -eq 0 ] && [ -f "$DIR/$o" ] && VNAMES+=("$o")
  done
fi

# probe every cut: length and real width x height (rotation applied)
PROBES=""
for d in "${VNAMES[@]}"; do
  p=$(ffprobe -v error -select_streams v:0 -show_entries stream=width,height:stream_side_data=rotation:stream_tags=rotate:format=duration -of json "$DIR/$d" 2>/dev/null)
  PROBES+="$p"$'\x1e'
done
VLIST=$(printf '%s;' "${VNAMES[@]}"); VLIST="${VLIST%;}"

python3 - "$LIB" "$REL" "$BRAND" "$TYPE" "$WHAT" "$STATUS" "${SV[0]}" "$VLIST" "$PROBES" <<'PY' || die 3 "index update failed"
import os, sys, json
lib, rel, brand, typ, what, status, source, vlist, probes = sys.argv[1:10]
COLS = ['folder', 'brand', 'type', 'what', 'length', 'aspect', 'status', 'source', 'copy', 'videos']
def fmt_len(s):
    s = int(round(s)); h, m, sec = s // 3600, (s % 3600) // 60, s % 60
    return '%d:%02d:%02d' % (h, m, sec) if h else '%d:%02d' % (m, sec)
def aspect(w, h):
    from math import gcd
    g = gcd(w, h); a, b = w // g, h // g
    named = {(16, 9): '16:9', (9, 16): '9:16', (1, 1): '1:1', (4, 5): '4:5', (4, 3): '4:3', (3, 4): '3:4'}
    r = w / h
    label = named.get((a, b))
    if not label:
        for (x, y), n in named.items():
            if abs(r - x / y) < 0.01: label = '~' + n
    return '%s %dx%d' % (label or ('%.2f:1' % r), w, h)
lens, asps = [], []
for p in [x for x in probes.split('\x1e') if x.strip()]:
    try:
        j = json.loads(p); s = j['streams'][0]; w, h = s['width'], s['height']
        rot = 0
        for sd in s.get('side_data_list', []) or []:
            if 'rotation' in sd: rot = int(sd['rotation'])
        if 'tags' in s and 'rotate' in s['tags']: rot = int(s['tags']['rotate'])
        if abs(rot) in (90, 270): w, h = h, w
        lens.append(fmt_len(float(j['format']['duration']))); asps.append(aspect(w, h))
    except Exception:
        lens.append('?'); asps.append('?')
def uniq(xs):
    out = []
    for x in xs:
        if x not in out: out.append(x)
    return ' / '.join(out)
idx = os.path.join(lib, '.index.tsv')
rows = []
if os.path.exists(idx):
    lines = open(idx, encoding='utf-8').read().split('\n')
    head = lines[0].split('\t') if lines else COLS
    rows = [dict(zip(head, l.split('\t'))) for l in lines[1:] if l.strip()]
old = next((r for r in rows if r['folder'] == rel), None)
import re
EM, EN = '\u2014', '\u2013'
def prose(s):  # the owner's copy has no em or en dashes (same rules as the bridge normalizer)
    s = re.sub(r'(\d)[^\S\n]*%s[^\S\n]*(\d)' % EN, r'\1 to \2', s)
    s = re.sub(r'[^\S\n]*%s[^\S\n]*$' % EM, '.', s)
    s = re.sub(r'^[^\S\n]*%s[^\S\n]*' % EM, '', s)
    s = re.sub(r'[^\S\n]*%s[^\S\n]*' % EM, ', ', s)
    return re.sub(r',\s*([,.;:!?])', r'\1', s.replace(EN, '-'))
new = dict(folder=rel, brand=brand, type=typ, what=prose(what) if what else (old['what'] if old else ''), length=uniq(lens),
           aspect=uniq(asps), status=status, source=source.replace(EM, '*').replace(EN, '*'), copy='clone', videos=vlist)
rows = [r for r in rows if r['folder'] != rel] + [new]
def clean(v):
    return str(v or '').replace('\t', ' ').replace('\n', ' ').replace('\r', ' ')
tmp = idx + '.tmp'
with open(tmp, 'w', encoding='utf-8') as f:
    f.write('\t'.join(COLS) + '\n')
    for r in rows: f.write('\t'.join(clean(r.get(k, '')) for k in COLS) + '\n')
os.replace(tmp, idx)
print('%s %s: %s, %s, %s' % ('updated' if old else 'added', rel, new['length'], new['aspect'], status))
PY
render || die 3 "README render failed"
